// schemaFS is the embedded copy of the generated schema sets. The files live in
// the tools/templates/ directory so the schema generator can rewrite them in
// place, which means the //go:embed directive has to sit in that package; it is
// re-exported here under the name the rest of this package uses.
var schemaFS = templates.FS

// templateRoot is the on-disk location of the schema set, relative to the
// working directory, probed for developer overrides before falling back to the
// embedded copy. It must stay in sync with the //go:embed package.
const templateRoot = "tools/templates"

// templateRootLegacy is the pre-move location, still probed so an existing
// checkout keeps working after the schemas move under tools/.
const templateRootLegacy = "templates"

// versionFileName is the manifest written by cmd/schema-gen
// that records every available template version and the latest one. The
// registry reads it so version names are data-driven instead of hard-coded.
const versionFileName = "template-version.json"

// Template versions shipped with occ live in template-v* subfolders
// under tools/templates/. Each folder holds only the JSON schema files
// generated by cmd/schema-gen; the registry code below is shared and
// links with any available version listed in template-version.json.

// LatestVersion is the default template version used when the user has not
// selected another one explicitly. It is populated from template-version.json
// at startup.
var LatestVersion string

// versionsOnce guards the one-time population of LatestVersion and
// availableVersions from template-version.json.
var (
	versionsOnce sync.Once
	versionsErr  error
)

// loadVersions reads template-version.json (preferring the on-disk copy so a
// freshly generated manifest takes effect without rebuilding) and populates
// LatestVersion and availableVersions.
func loadVersions() {
	versionsOnce.Do(func() {
		file := templatever.File{}
		for _, c := range versionFileCandidates() {
			data, err := os.ReadFile(c)
			if err == nil {
				file, err = templatever.Parse(data)
				if err != nil {
					versionsErr = fmt.Errorf("parse %s: %w", c, err)
					return
				}
				populateVersions(file)
				return
			}
		}
		data, err := schemaFS.ReadFile(versionFileName)
		if err != nil {
			versionsErr = fmt.Errorf("read %s: %w", versionFileName, err)
			return
		}
		file, err = templatever.Parse(data)
		if err != nil {
			versionsErr = fmt.Errorf("parse %s: %w", versionFileName, err)
			return
		}
		populateVersions(file)
	})
}

// populateVersions installs the parsed manifest into the package-level state.
func populateVersions(f templatever.File) {
	versions := make([]string, 0, len(f.Versions))
	set := make(map[string]bool, len(f.Versions))
	for _, v := range f.Versions {
		if v == "" || set[v] {
			continue
		}
		set[v] = true
		versions = append(versions, v)
	}
	availableVersions = versions
	LatestVersion = f.Latest
	if LatestVersion == "" || !contains(availableVersions, LatestVersion) {
		LatestVersion = latestOf(versions)
	}
}

// latestOf returns the greatest version of the given list.
func latestOf(versions []string) string {
	if len(versions) == 0 {
		return ""
	}
	best := versions[0]
	for _, v := range versions[1:] {
		if templatever.Compare(v, best) > 0 {
			best = v
		}
	}
	return best
}

// contains reports whether v is present in versions.
func contains(versions []string, v string) bool {
	for _, x := range versions {
		if x == v {
			return true
		}
	}
	return false
}

// versionFileCandidates lists the on-disk locations probed for the manifest
// before falling back to the embedded copy.
func versionFileCandidates() []string {
	exeDir := ""
	if exe, err := os.Executable(); err == nil {
		exeDir = filepath.Dir(exe)
	}
	candidates := []string{versionFileName}
	if exeDir != "" {
		candidates = append(candidates, filepath.Join(exeDir, versionFileName))
	}
	for _, base := range []string{
		filepath.Join(templateRoot, versionFileName),
		filepath.Join(templateRootLegacy, versionFileName),
	} {
		candidates = append(candidates, base)
	}
	return candidates
}

// AvailableVersions returns the names of every template version shipped with
// occ, sorted ascending.
func AvailableVersions() []string {
	loadVersions()
	out := make([]string, len(availableVersions))
	copy(out, availableVersions)
	return out
}

