var (
	kindIndex         = make(map[string]kindSpec, len(kinds))
	allKindNames      = make([]string, 0, len(kinds))
	loadOnce          sync.Once
	loadErr           error
	currentVersionVal atomic.Value
	availableVersions []string
)

// init stores the default template version. It must run after loadVersions so
// SchemaFor/RulesForKind work even before SetVersion is called.
func init() {
	loadVersions()
	currentVersionVal.Store(LatestVersion)
}

// currentVersion returns the active template version as a string.
func currentVersion() string {
	return currentVersionVal.Load().(string)
}

// load builds the versioned schema maps and the kind-name index. It is called
// lazily on first use and reports failures as errors instead of panicking.
func load() error {
	loadOnce.Do(func() {
		for _, ks := range kinds {
			kindIndex[ks.kind] = ks
			allKindNames = append(allKindNames, ks.kind)
		}
		schemasByVersion = make(map[string]map[string]*schema.FieldSchema, len(availableVersions))
		for _, ver := range availableVersions {
			byKind := make(map[string]*schema.FieldSchema, len(kinds))
			for _, ks := range kinds {
				data, err := readSchemaFile(ver, ks.file)
				if err != nil {
					loadErr = fmt.Errorf("read schema %s (template %s): %w", ks.file, ver, err)
					return
				}
				parsed, err := schema.Parse(data)
				if err != nil {
					loadErr = fmt.Errorf("parse schema %s (template %s): %w", ks.file, ver, err)
					return
				}
				byKind[ks.kind] = parsed
			}
			schemasByVersion[ver] = byKind
		}
	})
	return loadErr
}

// schemasByVersion holds the parsed FieldSchema for every kind per template
// version. It is populated by load and read-only afterwards.
var schemasByVersion map[string]map[string]*schema.FieldSchema

// SetVersion selects the template version used by SchemaFor, RulesForKind,
// and AllKinds. It accepts a concrete version such as "v1.2.0" or the alias
// "latest" (which maps to LatestVersion). An unknown version is rejected with
// an error listing the available versions.
func SetVersion(version string) error {
	if version == "" || version == "latest" {
		version = LatestVersion
	}
	for _, v := range availableVersions {
		if version == v {
			// Eagerly load so a bad/broken version surfaces before it is used.
			if err := load(); err != nil {
				return fmt.Errorf("load template %s: %w", version, err)
			}
			currentVersionVal.Store(version)
			return nil
		}
	}
	return fmt.Errorf("unknown template version %q (available: %s)", version, strings.Join(availableVersions, ", "))
}

// CurrentVersion returns the active template version. When no explicit
// selection has been made it returns LatestVersion.
func CurrentVersion() string {
	return currentVersion()
}

// LoadError returns the error that occurred while loading the template
// version manifest or the schema registry, or nil when both loaded
// successfully or have not been loaded yet.
func LoadError() error {
	loadVersions()
	if versionsErr != nil {
		return versionsErr
	}
	return load()
}

// SchemaFor returns the parsed FieldSchema for the given kind in the active
// template version, or nil if unknown.
func SchemaFor(kind string) *schema.FieldSchema {
	if load() != nil {
		return nil
	}
	return schemasByVersion[currentVersion()][kind]
}

// versionDir returns the subdirectory holding the schema files for a version.
func versionDir(version string) string {
	return "template-" + version
}

// readSchemaFile loads a schema JSON file for the given template version,
// preferring the on-disk copy so that edits take effect without rebuilding.
func readSchemaFile(version, file string) ([]byte, error) {
	dir := "template-" + version
	exeDir := ""
	if exe, err := os.Executable(); err == nil {
		exeDir = filepath.Dir(exe)
	}
	candidates := []string{file}
	if exeDir != "" {
		candidates = append(candidates, filepath.Join(exeDir, file))
	}
	for _, base := range []string{
		filepath.Join(templateRoot, dir),
		filepath.Join(templateRootLegacy, dir),
	} {
		candidates = append(candidates, filepath.Join(base, file))
	}
	for _, c := range candidates {
		data, err := os.ReadFile(c)
		if err == nil {
			return data, nil
		}
	}
	return schemaFS.ReadFile(filepath.Join(dir, file))
}
